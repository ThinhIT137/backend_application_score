import pytest
from datetime import datetime
from fastapi.testclient import TestClient
from jose import jwt
from src.app import app
from src.core.config import get_settings
from src.core.security import _normalize_role, decode_token, CurrentUser
from fastapi.security import HTTPAuthorizationCredentials

client = TestClient(app)
settings = get_settings()


def create_token(payload: dict) -> str:
    return jwt.encode(payload, settings.jwt_secret, algorithm=settings.jwt_algorithm)


def test_config_reads_jwt_accesstoken():
    assert settings.jwt_secret is not None
    assert len(settings.jwt_secret) > 0
    assert settings.jwt_algorithm == "HS256"


def test_normalize_role():
    assert _normalize_role("super_admin") == "admin"
    assert _normalize_role("chuyen_vien") == "admin"
    assert _normalize_role("admin") == "admin"
    assert _normalize_role("thi_sinh") == "thi_sinh"
    assert _normalize_role("unknown_role") is None
    assert _normalize_role(None) is None


def test_decode_token_super_admin():
    token = create_token({
        "role": "super_admin",
        "ma_admin": "adm-001",
        "sub": "adm-001",
    })
    creds = HTTPAuthorizationCredentials(scheme="Bearer", credentials=token)
    user = decode_token(creds)
    assert user.role == "admin"
    assert user.admin_role == "super_admin"
    assert user.ma_admin == "adm-001"


