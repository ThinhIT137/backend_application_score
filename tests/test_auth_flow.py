def test_ho_so_requires_admin_token():
    # Missing token -> 401
    resp = client.get("/ho-so")
    assert resp.status_code == 401
    assert "token" in resp.json().get("detail", "").lower()

    # Invalid token -> 401
    resp = client.get("/ho-so", headers={"Authorization": "Bearer invalid_token_123"})
    assert resp.status_code == 401

    # Thi sinh token -> 403 Forbidden
    student_token = create_token({"role": "thi_sinh", "cccd": "012345678901"})
    resp = client.get("/ho-so", headers={"Authorization": f"Bearer {student_token}"})
    assert resp.status_code == 403

    # Admin token -> Accepted (passes security check, status is 200 or DB response)
    admin_token = create_token({"role": "super_admin", "ma_admin": "adm-001"})
    resp = client.get("/ho-so", headers={"Authorization": f"Bearer {admin_token}"})
    assert resp.status_code in {200, 500}  # 200 if DB reachable, not 401/403


def test_dgnl_nop_does_not_require_jwt():
    # Calling POST /diem/dgnl without Authorization header
    resp = client.post(
        "/diem/dgnl",
        json={
            "cccd": "999999999999",
            "diem": 110.5,
            "ngay_cap": datetime.now().isoformat(),
            "file_dinh_kem": "https://storage.example.com/dgnl.pdf",
        },
    )
    # Must NOT return 401 Unauthorized (JWT check removed)
    assert resp.status_code != 401
    # Returns 400 because CCCD does not exist in DB, proving it passed auth and reached service validation!
    assert resp.status_code in {400, 422}
